-- =====================================================================
-- WIJHA – 04_reservations.sql : réservations liées aux comptes clients
-- Supabase > SQL Editor > New query > coller > Run
-- (à exécuter après 01_schema.sql et 02_seed.sql ; indépendant de 03_dinars.sql)
--
-- Principes :
--   - une réservation porte sur UNE voiture (une immatriculation) ;
--   - la base interdit deux réservations actives qui se chevauchent sur la même
--     voiture (contrainte d'exclusion), même si deux clients valident en même temps ;
--   - un client ne lit que SES réservations (RLS) ; il crée et annule uniquement
--     par les fonctions creer_reservation() et annuler_reservation() ;
--   - periodes_occupees() donne au site les créneaux pris, sans dire par qui.
-- =====================================================================

set search_path = public, extensions;
create extension if not exists btree_gist with schema extensions;

-- ---------------------------------------------------------------------
-- 0) Une ancienne table « reservations » (autre modèle, sans user_id) existe déjà :
--    elle est mise de côté dans le schéma « archive », PAS supprimée.
--    Pour la supprimer plus tard : drop table archive.reservations cascade;
-- ---------------------------------------------------------------------
do $$
begin
    if exists (select 1 from information_schema.tables
               where table_schema = 'public' and table_name = 'reservations')
       and not exists (select 1 from information_schema.columns
               where table_schema = 'public' and table_name = 'reservations' and column_name = 'user_id') then
        create schema if not exists archive;
        alter table public.reservations set schema archive;
        raise notice 'Ancienne table reservations déplacée dans archive.reservations';
    end if;
end $$;

-- ---------------------------------------------------------------------
-- 1) Table
-- ---------------------------------------------------------------------
create table if not exists public.reservations (
    id                bigint generated by default as identity primary key,
    ref               text        not null unique,                 -- WJH-AAMMJJ-XXXX
    user_id           uuid        not null default auth.uid() references auth.users (id) on delete cascade,
    vehicule_id       bigint      not null references public.vehicules (id),
    agence_depart_id  smallint    not null references public.agences (id),
    agence_retour_id  smallint    not null references public.agences (id),
    debut             timestamptz not null,
    fin               timestamptz not null,
    options           text[]      not null default '{}',
    lignes            jsonb       not null default '[]',            -- détail du prix affiché au client
    total_tnd         numeric(10,2) not null check (total_tnd >= 0),
    conducteur_age    text,
    voyageurs         smallint    check (voyageurs between 1 and 20),
    bagages           smallint    check (bagages between 0 and 30),
    client_prenom     text        not null,
    client_nom        text        not null,
    client_email      text        not null,
    client_tel        text        not null,
    vol               text,
    statut            text        not null default 'en_attente'
                      check (statut in ('en_attente', 'confirmee', 'annulee', 'terminee')),
    created_at        timestamptz not null default now(),
    updated_at        timestamptz not null default now(),

    constraint reservations_dates check (fin > debut),
    -- Pas de chevauchement sur une même voiture tant que la réservation est active.
    constraint reservations_sans_chevauchement exclude using gist (
        vehicule_id with =,
        tstzrange(debut, fin) with &&
    ) where (statut in ('en_attente', 'confirmee'))
);
comment on table public.reservations is 'Réservations des clients (une voiture, une période)';

create index if not exists reservations_user_idx     on public.reservations (user_id);
create index if not exists reservations_vehicule_idx on public.reservations (vehicule_id);

-- (Re)définie ici au cas où 01_schema.sql n'a pas été exécuté tel quel sur la base.
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end $$;

drop trigger if exists reservations_set_updated_at on public.reservations;
create trigger reservations_set_updated_at
before update on public.reservations
for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- 2) Sécurité : chaque client ne voit que ses réservations.
--    Aucune policy d'écriture : création et annulation passent par les fonctions.
-- ---------------------------------------------------------------------
alter table public.reservations enable row level security;

drop policy if exists "client lit ses reservations" on public.reservations;
create policy "client lit ses reservations" on public.reservations
    for select to authenticated using (user_id = auth.uid());

-- ---------------------------------------------------------------------
-- 3) Créneaux occupés (pour calculer la disponibilité dans le catalogue)
-- ---------------------------------------------------------------------
create or replace function public.periodes_occupees()
returns table (vehicule_id bigint, debut timestamptz, fin timestamptz)
language sql stable security definer set search_path = public
as $$
    select r.vehicule_id, r.debut, r.fin
    from public.reservations r
    where r.statut in ('en_attente', 'confirmee') and r.fin > now();
$$;

-- ---------------------------------------------------------------------
-- 4) Créer une réservation
--    p_vehicules : voitures acceptables (celles du modèle choisi), par ordre de préférence.
--    La fonction prend la première libre à l'agence de départ et l'enregistre.
-- ---------------------------------------------------------------------
create or replace function public.creer_reservation(
    p_vehicules      bigint[],
    p_agence_depart  text,
    p_agence_retour  text,
    p_debut          timestamptz,
    p_fin            timestamptz,
    p_options        text[],
    p_lignes         jsonb,
    p_total          numeric,
    p_age            text,
    p_voyageurs      smallint,
    p_bagages        smallint,
    p_prenom         text,
    p_nom            text,
    p_email          text,
    p_tel            text,
    p_vol            text
)
returns table (ref text, vehicule_id bigint, immatriculation text)
language plpgsql security definer set search_path = public
as $$
#variable_conflict use_column
declare
    v_user     uuid := auth.uid();
    v_depart   smallint;
    v_retour   smallint;
    v_voiture  bigint;
    v_ref      text;
    v_essai    int := 0;
begin
    if v_user is null then
        raise exception 'Connexion requise' using errcode = '28000';
    end if;
    if p_fin <= p_debut then
        raise exception 'La date de retour doit être après le retrait' using errcode = '22023';
    end if;
    if p_debut < now() - interval '5 minutes' then
        raise exception 'Le retrait doit être dans le futur' using errcode = '22023';
    end if;

    select a.id into v_depart from public.agences a where a.ville = p_agence_depart;
    select a.id into v_retour from public.agences a where a.ville = coalesce(nullif(p_agence_retour, ''), p_agence_depart);
    if v_depart is null or v_retour is null then
        raise exception 'Agence inconnue' using errcode = '22023';
    end if;

    -- Première voiture du modèle, disponible à l'agence de départ, sans réservation qui chevauche.
    select v.id into v_voiture
    from public.vehicules v
    where v.id = any (p_vehicules)
      and v.agence_id = v_depart
      and v.statut = 'disponible'
      and not exists (
          select 1 from public.reservations r
          where r.vehicule_id = v.id
            and r.statut in ('en_attente', 'confirmee')
            and tstzrange(r.debut, r.fin) && tstzrange(p_debut, p_fin))
    order by array_position(p_vehicules, v.id)
    limit 1
    for update of v skip locked;

    if v_voiture is null then
        raise exception 'Aucune voiture de ce modèle n''est libre à ces dates dans cette agence' using errcode = 'P0001';
    end if;

    -- Référence unique (nouvel essai en cas de collision, très improbable).
    loop
        v_essai := v_essai + 1;
        v_ref := 'WJH-' || to_char(now() at time zone 'Africa/Tunis', 'YYMMDD') || '-'
                 || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 4));
        begin
            insert into public.reservations (
                ref, user_id, vehicule_id, agence_depart_id, agence_retour_id, debut, fin,
                options, lignes, total_tnd, conducteur_age, voyageurs, bagages,
                client_prenom, client_nom, client_email, client_tel, vol)
            values (
                v_ref, v_user, v_voiture, v_depart, v_retour, p_debut, p_fin,
                coalesce(p_options, '{}'), coalesce(p_lignes, '[]'), p_total, p_age, p_voyageurs, p_bagages,
                p_prenom, p_nom, p_email, p_tel, nullif(p_vol, ''));
            exit;
        exception when unique_violation then
            if v_essai >= 5 then raise; end if;
        end;
    end loop;

    -- Conversions explicites : sur la base réelle, id et immatriculation n'ont pas
    -- forcément les types bigint / text de 01_schema.sql.
    return query
        select v_ref::text, v.id::bigint, v.immatriculation::text from public.vehicules v where v.id = v_voiture;
end $$;

-- ---------------------------------------------------------------------
-- 5) Annuler une de ses réservations (avant le début de la location)
-- ---------------------------------------------------------------------
create or replace function public.annuler_reservation(p_ref text)
returns boolean
language plpgsql security definer set search_path = public
as $$
declare
    n int;
begin
    update public.reservations
       set statut = 'annulee'
     where ref = p_ref
       and user_id = auth.uid()
       and statut in ('en_attente', 'confirmee')
       and debut > now();
    get diagnostics n = row_count;
    return n > 0;
end $$;

-- ---------------------------------------------------------------------
-- 6) Droits d'exécution
-- ---------------------------------------------------------------------
revoke all on function public.periodes_occupees() from public;
revoke all on function public.creer_reservation(bigint[], text, text, timestamptz, timestamptz, text[], jsonb, numeric, text, smallint, smallint, text, text, text, text, text) from public;
revoke all on function public.annuler_reservation(text) from public;
grant execute on function public.periodes_occupees() to anon, authenticated;
grant execute on function public.creer_reservation(bigint[], text, text, timestamptz, timestamptz, text[], jsonb, numeric, text, smallint, smallint, text, text, text, text, text) to authenticated;
grant execute on function public.annuler_reservation(text) to authenticated;

notify pgrst, 'reload schema';
