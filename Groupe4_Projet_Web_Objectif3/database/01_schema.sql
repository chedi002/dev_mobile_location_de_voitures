-- ---------------------------------------------------------------------
-- 1) categories
-- ---------------------------------------------------------------------
create table public.categories (
    id           smallint primary key,
    code         text     not null unique,
    nom          text     not null,
    description  text
);
comment on table public.categories is 'Catégories de véhicules (citadine, SUV, minibus, premium…)';

-- ---------------------------------------------------------------------
-- 2) agences
-- ---------------------------------------------------------------------
create table public.agences (
    id         smallint primary key,
    nom        text not null,
    ville      text not null,
    adresse    text,
    telephone  text,
    horaires   text,
    latitude   numeric(9,6) check (latitude  between -90  and 90),
    longitude  numeric(9,6) check (longitude between -180 and 180)
);
comment on table public.agences is 'Agences de location (une ville = une agence)';

-- ---------------------------------------------------------------------
-- 3) statuts_vehicule  (table de référence : on peut ajouter un état sans migration)
-- ---------------------------------------------------------------------
create table public.statuts_vehicule (
    code         text primary key,
    libelle      text    not null,
    description  text,
    reservable   boolean not null default false   -- true = peut être proposé à la réservation
);
comment on table public.statuts_vehicule is 'États possibles d''un véhicule';

-- ---------------------------------------------------------------------
-- 4) vehicules
-- ---------------------------------------------------------------------
create table public.vehicules (
    id                  bigint generated by default as identity primary key,
    marque              text     not null,
    modele              text     not null,
    annee               smallint not null check (annee between 2015 and 2035),
    categorie_id        smallint not null references public.categories (id),
    places              smallint not null check (places between 1 and 9),
    portes              smallint not null check (portes between 2 and 5),
    bagages_valises     smallint not null default 0 check (bagages_valises >= 0),
    transmission        text     not null check (transmission in ('Manuelle', 'Automatique')),
    carburant           text     not null check (carburant in ('Essence', 'Diesel', 'Hybride', 'Électrique')),
    climatisation       boolean  not null default true,
    prix_jour_eur       numeric(8,2) not null check (prix_jour_eur > 0),
    depot_garantie_eur  numeric(8,2) not null default 0 check (depot_garantie_eur >= 0),
    agence_id           smallint not null references public.agences (id),
    immatriculation     text     not null unique,
    statut              text     not null default 'disponible' references public.statuts_vehicule (code),
    equipements         text[]   not null default '{}',
    tags_voyage         text[]   not null default '{}',
    image_principale    text,
    description         text,
    created_at          timestamptz not null default now(),
    updated_at          timestamptz not null default now(),

    -- Matricule tunisien « NNN TUN NNNN » avec numéro de série >= 240
    constraint vehicules_immat_format
        check (immatriculation ~ '^[0-9]{3} TUN [0-9]{1,4}$'),
    constraint vehicules_immat_serie_min_240
        check (split_part(immatriculation, ' ', 1)::int >= 240)
);
comment on table  public.vehicules is 'Flotte de véhicules WIJHA';
comment on column public.vehicules.immatriculation is 'Format NNN TUN NNNN, série >= 240';
comment on column public.vehicules.statut is 'Voir table statuts_vehicule. Archiver (inactif) plutôt que supprimer.';

-- Index utiles pour le catalogue et les filtres
create index vehicules_agence_idx    on public.vehicules (agence_id);
create index vehicules_categorie_idx on public.vehicules (categorie_id);
create index vehicules_statut_idx    on public.vehicules (statut);
create index vehicules_prix_idx      on public.vehicules (prix_jour_eur);
create index vehicules_tags_gin_idx  on public.vehicules using gin (tags_voyage);

-- ---------------------------------------------------------------------
-- 5) updated_at automatique
-- ---------------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger language plpgsql as $$
begin
    new.updated_at = now();
    return new;
end $$;

create trigger vehicules_set_updated_at
before update on public.vehicules
for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------
-- 6) Vue prête à l'emploi pour le site (jointures déjà faites)
-- ---------------------------------------------------------------------
create or replace view public.vue_vehicules_catalogue
with (security_invoker = true) as
select  v.id, v.marque, v.modele, v.annee,
        c.code as categorie_code, c.nom as categorie,
        v.places, v.portes, v.bagages_valises, v.transmission, v.carburant,
        v.climatisation, v.prix_jour_eur, v.depot_garantie_eur,
        a.id as agence_id, a.nom as agence, a.ville,
        v.immatriculation,
        v.statut, s.libelle as statut_libelle, s.reservable,
        v.equipements, v.tags_voyage, v.image_principale, v.description
from public.vehicules v
join public.categories       c on c.id   = v.categorie_id
join public.agences          a on a.id   = v.agence_id
join public.statuts_vehicule s on s.code = v.statut;

-- ---------------------------------------------------------------------
-- 7) Sécurité (Row Level Security)
--    Lecture publique du catalogue ; écriture réservée à la clé service_role
--    (ou à des policies que vous ajouterez pour vos administrateurs).
-- ---------------------------------------------------------------------
alter table public.categories       enable row level security;
alter table public.agences          enable row level security;
alter table public.statuts_vehicule enable row level security;
alter table public.vehicules        enable row level security;

create policy "lecture publique categories" on public.categories
    for select to anon, authenticated using (true);
create policy "lecture publique agences" on public.agences
    for select to anon, authenticated using (true);
create policy "lecture publique statuts" on public.statuts_vehicule
    for select to anon, authenticated using (true);
create policy "lecture publique vehicules" on public.vehicules
    for select to anon, authenticated using (true);
