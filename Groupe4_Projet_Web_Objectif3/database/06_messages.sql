-- =====================================================================
-- WIJHA – 06_messages.sql : messages de contact et demandes de transfert
-- Supabase > SQL Editor > New query > coller > Run
-- (après 05_admin.sql : utilise est_admin())
--
--   - tout visiteur, connecté ou non, peut ENVOYER un message ou une demande ;
--   - seuls les administrateurs peuvent les LIRE et les marquer comme traités ;
--   - des contraintes de longueur limitent les abus.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) Messages du formulaire de contact
-- ---------------------------------------------------------------------
create table if not exists public.messages_contact (
    id          bigint generated by default as identity primary key,
    created_at  timestamptz not null default now(),
    user_id     uuid default auth.uid() references auth.users (id) on delete set null,
    prenom      text not null check (char_length(prenom) between 1 and 80),
    nom         text not null check (char_length(nom) between 1 and 80),
    email       text not null check (char_length(email) between 5 and 200 and email like '%@%.%'),
    tel         text check (char_length(tel) <= 30),
    sujet       text not null check (char_length(sujet) between 1 and 80),
    reference   text check (char_length(reference) <= 30),
    message     text not null check (char_length(message) between 20 and 4000),
    traite      boolean not null default false
);
comment on table public.messages_contact is 'Messages envoyés depuis la page Contact';

-- ---------------------------------------------------------------------
-- 2) Demandes de transfert aéroport
-- ---------------------------------------------------------------------
create table if not exists public.demandes_transfert (
    id          bigint generated by default as identity primary key,
    created_at  timestamptz not null default now(),
    user_id     uuid default auth.uid() references auth.users (id) on delete set null,
    sens        text not null check (sens in ('arrivee', 'depart')),
    aeroport    text not null check (char_length(aeroport) between 1 and 80),
    lieu        text not null check (char_length(lieu) between 1 and 200),
    quand       timestamptz not null,
    vol         text check (char_length(vol) <= 20),
    passagers   smallint not null check (passagers between 1 and 16),
    bagages     smallint not null default 0 check (bagages between 0 and 20),
    besoins     text check (char_length(besoins) <= 1000),
    nom         text not null check (char_length(nom) between 1 and 120),
    email       text not null check (char_length(email) between 5 and 200 and email like '%@%.%'),
    traite      boolean not null default false
);
comment on table public.demandes_transfert is 'Demandes envoyées depuis la page Transfert aéroport';

-- ---------------------------------------------------------------------
-- 3) Sécurité
-- ---------------------------------------------------------------------
alter table public.messages_contact   enable row level security;
alter table public.demandes_transfert enable row level security;

-- Envoi ouvert à tous (le statut « traité » ne peut pas être choisi à l'envoi)
drop policy if exists "envoi message contact" on public.messages_contact;
create policy "envoi message contact" on public.messages_contact
    for insert to anon, authenticated with check (traite = false);
drop policy if exists "envoi demande transfert" on public.demandes_transfert;
create policy "envoi demande transfert" on public.demandes_transfert
    for insert to anon, authenticated with check (traite = false);

-- Lecture et suivi réservés aux administrateurs
drop policy if exists "admin lit messages contact" on public.messages_contact;
create policy "admin lit messages contact" on public.messages_contact
    for select to authenticated using (public.est_admin());
drop policy if exists "admin traite messages contact" on public.messages_contact;
create policy "admin traite messages contact" on public.messages_contact
    for update to authenticated using (public.est_admin()) with check (public.est_admin());

drop policy if exists "admin lit demandes transfert" on public.demandes_transfert;
create policy "admin lit demandes transfert" on public.demandes_transfert
    for select to authenticated using (public.est_admin());
drop policy if exists "admin traite demandes transfert" on public.demandes_transfert;
create policy "admin traite demandes transfert" on public.demandes_transfert
    for update to authenticated using (public.est_admin()) with check (public.est_admin());

-- Un admin ne peut modifier que la case « traité »
revoke update on public.messages_contact, public.demandes_transfert from anon, authenticated;
grant update (traite) on public.messages_contact, public.demandes_transfert to authenticated;

notify pgrst, 'reload schema';
